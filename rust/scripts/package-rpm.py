"""Build the memveil .rpm from the Rust owner bundle.

Builds the memveil .rpm from the input tree: Source0 is the
tree's own file set at HEAD (overlaid with the packager's own
generator inputs from the running tree), and the spec copies
the verified bundle without recompiling. Prints
"package-rpm: <path>" with the built .rpm on success.

Usage: rust/scripts/package-rpm.py --work DIR --out DIR [--bundle DIR]
    [--root DIR] [--binary PATH] [--bpf-dir DIR] [--build]
  --work DIR   scratch directory (required)
  --out DIR    output directory (required)
  --bundle DIR consume an existing verified bundle without building
  --root/--binary/--bpf-dir/--build  bundle-build inputs, used only
      without --bundle (see package-tarball.py); --root also
      selects the Source0 tree and must be a clean checkout

Exit 0 on success; exit 1 when the build fails. One action per
invocation; extra arguments are rejected. The input tree must
be clean (a dirty tree cannot produce a candidate Source0).
"""

import gzip
import hashlib
import io
import json
import os
import shutil
import subprocess
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
RUN_RUST_DIR = os.path.dirname(HERE)


def fail(message):
    print("package-rpm: %s" % message, file=sys.stderr)
    sys.exit(1)


def run(argv, **kwargs):
    proc = subprocess.run(
        argv, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        text=True, **kwargs,
    )
    return proc


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def verify_bundle(bundle):
    """Bundle MANIFEST re-verified; returns the manifest dict."""
    manifest_path = os.path.join(bundle, "MANIFEST.json")
    try:
        with open(manifest_path, "r", encoding="utf-8") as handle:
            manifest = json.load(handle)
    except (OSError, ValueError) as exc:
        fail("bundle MANIFEST unreadable: %s" % exc)
    if not manifest.get("engine_version") \
            or not manifest.get("memveil_revision") \
            or not manifest.get("files"):
        fail("bundle MANIFEST lacks identity")
    for rel, want in sorted(manifest["files"].items()):
        full = os.path.join(bundle, rel)
        if not os.path.isfile(full) or os.path.islink(full):
            fail("bundle payload missing: %s" % rel)
        if sha256_file(full) != want:
            fail("bundle payload differs from MANIFEST: %s" % rel)
    return manifest


def git_tree_clean(root):
    """True when root is an owning checkout with no changes."""
    top = run(["git", "-C", root, "rev-parse", "--show-toplevel"])
    if top.returncode != 0 or not top.stdout.strip() \
            or os.path.realpath(top.stdout.strip()) \
            != os.path.realpath(root):
        return False
    status = run(["git", "-C", root, "status", "--short"])
    return status.returncode == 0 and status.stdout.strip() == ""


def head_commit_time(root):
    proc = run(["git", "-C", root, "log", "-1", "--format=%ct"])
    if proc.returncode != 0:
        fail("cannot read HEAD commit time in %s" % root)
    return int(proc.stdout.strip())


def overlay_files():
    """Packager inputs overlaid onto Source0 from the running tree.

    Every path is rust/-relative; the spec's %install runs these
    generators, so they must match the running packager even
    when the tree has uncommitted packaging work. Returns
    {arcname suffix: disk path}.
    """
    found = {}
    for subdir in ("scripts", "packaging"):
        base = os.path.join(RUN_RUST_DIR, subdir)
        for current, dirs, files in os.walk(base):
            # Generated bytecode never joins the source export.
            dirs[:] = [name for name in dirs
                       if name != "__pycache__"
                       and not name.startswith(".")]
            for name in sorted(files):
                if name.endswith(".pyc") or name.startswith("."):
                    continue
                full = os.path.join(current, name)
                rel = os.path.relpath(full, RUN_RUST_DIR)
                found["rust/" + rel.replace(os.sep, "/")] = full
    if not found:
        fail("no packager inputs under %s" % RUN_RUST_DIR)
    return found


def build_source0(root, version, dest):
    """Write Source0: HEAD archive plus the packager overlay.

    `git archive HEAD` contributes the tree's own tracked file
    set (pure HEAD bytes, never worktree dirt); the running
    tree's rust/scripts plus rust/packaging overlay it so the
    spec's generators always match the running packager.
    Member mtimes pin to the HEAD commit time and the gzip
    header mtime is zero, so the same HEAD rebuilds
    byte-identically.
    """
    prefix = "memveil-%s/" % version
    archive = subprocess.run(
        ["git", "-C", root, "archive", "--format=tar",
         "--prefix=" + prefix, "HEAD"],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if archive.returncode != 0:
        fail("Source0 git archive failed: %s"
             % archive.stderr.decode("utf-8", "replace"))
    mtime = head_commit_time(root)
    overlay = overlay_files()
    overlaid = set()
    added = 0
    try:
        with open(dest, "wb") as raw:
            gz = gzip.GzipFile(filename="", mode="wb",
                               fileobj=raw, compresslevel=9,
                               mtime=0)
            try:
                with tarfile.open(
                        fileobj=io.BytesIO(archive.stdout),
                        mode="r|*") as src, \
                        tarfile.open(fileobj=gz, mode="w") as tar:
                    for member in src:
                        if member.issym() or member.islnk():
                            # Fixture symlinks are first-class
                            # tree members: preserve the link.
                            info = tarfile.TarInfo(member.name)
                            info.type = member.type
                            info.linkname = member.linkname
                            info.mtime = mtime
                            info.uid = info.gid = 0
                            info.uname = info.gname = ""
                            info.mode = 0o777
                            tar.addfile(info)
                            continue
                        if not (member.isfile() or member.isdir()):
                            continue
                        suffix = member.name[len(prefix):] \
                            if member.name.startswith(prefix) \
                            else member.name
                        # Overlay keys are rust/-relative paths.
                        disk = overlay.get(suffix) \
                            if suffix.startswith("rust/") else None
                        if member.isdir():
                            info = tarfile.TarInfo(member.name)
                            info.type = tarfile.DIRTYPE
                            info.mtime = mtime
                            info.uid = info.gid = 0
                            info.uname = info.gname = ""
                            info.mode = 0o755
                            tar.addfile(info)
                            continue
                        if disk is not None:
                            overlaid.add(suffix)
                            with open(disk, "rb") as handle:
                                data = handle.read()
                            keep_exec = bool(
                                os.stat(disk).st_mode & 0o111)
                        else:
                            extracted = src.extractfile(member)
                            if extracted is None:
                                continue
                            data = extracted.read()
                            keep_exec = bool(member.mode & 0o111)
                        info = tarfile.TarInfo(member.name)
                        info.size = len(data)
                        info.mtime = mtime
                        info.uid = info.gid = 0
                        info.uname = info.gname = ""
                        info.mode = 0o755 if keep_exec else 0o644
                        tar.addfile(info, io.BytesIO(data))
                    # Overlay files the archive lacks (uncommitted
                    # packager inputs) join under the same prefix.
                    for suffix in sorted(overlay):
                        if suffix in overlaid:
                            continue
                        added += 1
                        disk = overlay[suffix]
                        with open(disk, "rb") as handle:
                            data = handle.read()
                        # Every ancestor dir first: explicit
                        # members stay tidy (duplicates merge
                        # harmlessly on unpack).
                        ancestor = os.path.dirname(prefix + suffix)
                        chain = []
                        while ancestor and ancestor != prefix.rstrip("/"):
                            chain.append(ancestor)
                            ancestor = os.path.dirname(ancestor)
                        for ancestor in reversed(chain):
                            info = tarfile.TarInfo(ancestor)
                            info.type = tarfile.DIRTYPE
                            info.mtime = mtime
                            info.uid = info.gid = 0
                            info.uname = info.gname = ""
                            info.mode = 0o755
                            try:
                                tar.addfile(info)
                            except OSError:
                                pass
                        info = tarfile.TarInfo(prefix + suffix)
                        info.size = len(data)
                        info.mtime = mtime
                        info.uid = info.gid = 0
                        info.uname = info.gname = ""
                        info.mode = 0o755 \
                            if os.stat(disk).st_mode & 0o111 \
                            else 0o644
                        tar.addfile(info, io.BytesIO(data))
            finally:
                gz.close()
    except OSError as exc:
        fail("Source0 write failed: %s" % exc)
    print("package-rpm: Source0 %s (%d replaced, %d added "
          "packager inputs)" % (dest, len(overlaid), added))


def main(argv):
    work = None
    out_dir = None
    canonical_bundle = None
    root_opt = None
    passthrough = []
    bundle_only = False
    args = list(argv)
    while args:
        opt = args.pop(0)
        if opt in ("--help", "-h"):
            print(__doc__)
            return 0
        if opt == "--work" and args:
            work = args.pop(0)
            continue
        if opt == "--out" and args:
            out_dir = args.pop(0)
            continue
        if opt == "--bundle" and args:
            canonical_bundle = os.path.abspath(args.pop(0))
            continue
        if opt == "--root" and args:
            root_opt = args.pop(0)
            passthrough += [opt, root_opt]
            continue
        if opt in ("--binary", "--bpf-dir") and args:
            passthrough += [opt, args.pop(0)]
            bundle_only = True
            continue
        if opt == "--build":
            passthrough.append(opt)
            bundle_only = True
            continue
        fail("unknown option: %s" % opt)
    if canonical_bundle is not None and bundle_only:
        fail("--bundle cannot combine with bundle-build options "
             "(--binary/--bpf-dir/--build)")
    if work is None or out_dir is None:
        fail("want --work DIR --out DIR")
    if shutil.which("rpmbuild") is None:
        fail("BLOCKED: rpmbuild is not installed")

    # The Source0 tree: explicit --root or the running checkout,
    # always a clean owning checkout (dirty trees cannot
    # produce a candidate Source0).
    if root_opt is not None:
        root = os.path.abspath(root_opt)
    else:
        root = os.path.dirname(RUN_RUST_DIR)
    if not git_tree_clean(root):
        fail("Source0 tree is not a clean checkout: %s" % root)

    bundle = canonical_bundle
    if bundle is None:
        bundle_parent = os.path.join(work, "canonical")
        os.makedirs(bundle_parent, exist_ok=True)
        build = run([os.path.join(HERE, "package-tarball.py"),
                     "--out", bundle_parent, "--tag", "bundle"]
                    + passthrough)
        if build.returncode != 0:
            print(build.stdout)
            print(build.stderr, file=sys.stderr)
            fail("package-tarball.py failed")
        bundle = os.path.join(bundle_parent, "bundle")
    bundle = os.path.realpath(bundle)
    manifest = verify_bundle(bundle)
    engine = manifest["engine_version"]

    spec = os.path.join(RUN_RUST_DIR, "packaging", "rpm",
                        "memveil.spec")
    try:
        with open(spec, "r", encoding="utf-8") as handle:
            spec_text = handle.read()
    except OSError as exc:
        fail("spec unreadable: %s" % exc)
    spec_ver = None
    for line in spec_text.splitlines():
        if line.startswith("Version:"):
            spec_ver = line.split(":", 1)[1].strip()
    if not spec_ver:
        fail("spec has no Version tag")
    if spec_ver != engine:
        fail("spec Version %s vs engine %s: bump together"
             % (spec_ver, engine))

    rtop = os.path.join(work, "rpmbuild")
    for sub in ("SOURCES", "BUILD", "RPMS", "SRPMS", "BUILDROOT"):
        os.makedirs(os.path.join(rtop, sub), exist_ok=True)
    os.makedirs(out_dir, exist_ok=True)
    source0 = os.path.join(
        rtop, "SOURCES", "memveil-%s.tar.gz" % spec_ver)
    build_source0(root, spec_ver, source0)
    work_spec = os.path.join(work, "memveil.spec")
    shutil.copy2(spec, work_spec)
    # debug_package nil works around rpm builds that run
    # find-debuginfo despite the spec's __os_install_post nil;
    # it only gates the -debuginfo subpackage, never the main
    # payload. --nodeps: the host package manager, not the
    # (empty or absent) rpm db, provides the BuildRequires.
    env = dict(os.environ)
    env["MEMVEIL_CANONICAL_BUNDLE"] = bundle
    build = subprocess.run(
        ["rpmbuild", "-bb", "--nodeps",
         "--define", "_topdir %s" % rtop,
         "--define", "debug_package %{nil}", work_spec],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        text=True, env=env)
    with open(os.path.join(work, "rpmbuild.log"), "w") as handle:
        handle.write(build.stdout)
        handle.write(build.stderr)
    if build.returncode != 0:
        print("package-rpm: BLOCKED: rpmbuild failed", file=sys.stderr)
        print(build.stdout[-3000:])
        print(build.stderr[-3000:], file=sys.stderr)
        sys.exit(1)
    rpms = []
    for base, _, files in os.walk(os.path.join(rtop, "RPMS")):
        for name in files:
            if name.endswith(".rpm"):
                rpms.append(os.path.join(base, name))
    if len(rpms) != 1:
        fail("no .rpm built (see %s)"
             % os.path.join(work, "rpmbuild.log"))
    dest = os.path.join(out_dir, os.path.basename(rpms[0]))
    shutil.copy2(rpms[0], dest)
    print("package-rpm: %s" % dest)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
