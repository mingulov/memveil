"""Inventory and verify canonical runtime bytes, without granting qualification."""
import argparse
import hashlib
import json
import os
import re
from pathlib import Path
import stat
import runtime_cpu

FORMAT = 'memveil-runtime/1'


def parse_size(value):
    if (not isinstance(value, str) or len(value) > 20 or
            re.fullmatch(r'0|[1-9][0-9]*', value) is None):
        raise ValueError('runtime size must be a canonical unsigned decimal string')
    size = int(value)
    if size > 18446744073709551615:
        raise ValueError('runtime size exceeds unsigned 64-bit range')
    return size


def digest(path):
    h = hashlib.sha256()
    with open(path, 'rb') as stream:
        for chunk in iter(lambda: stream.read(1048576), b''):
            h.update(chunk)
    return h.hexdigest()


def installed_path(name):
    if name == 'bin/memveil' or name.startswith('lib/memveil/'):
        return 'usr/' + name
    if name.startswith('bpf/'):
        return 'usr/lib/memveil/' + name[4:]
    if name.startswith('profiles/'):
        return 'usr/share/memveil/' + name
    raise ValueError('unknown runtime path: ' + name)


def installed_file_path(name):
    """Map every sealed bundle file copied into either system package."""
    if (not isinstance(name, str) or not name or name.startswith('/') or
            any(part in ('', '.', '..') for part in name.split('/'))):
        raise ValueError('invalid bundle file path')
    if name.startswith(('docs/', 'profiles/')):
        return 'usr/share/memveil/' + name
    if name.startswith('examples/'):
        return 'usr/share/memveil/docs/' + name
    if name in ('LICENSE', 'THIRD-PARTY-NOTICES.md',
                'THIRD-PARTY-NOTICES.libbpf-mojo.md') or name.startswith(('LICENSES/', 'licenses/')):
        return 'usr/share/doc/memveil/' + name
    return installed_path(name)


def verify_installed(root, manifest):
    """Bind copied destinations to the manifest saved before copying."""
    root = Path(root)
    verify(root, manifest['canonical_runtime']['entries'], installed=True)
    expected = {}
    for name, sha256 in manifest['files'].items():
        target = installed_file_path(name)
        if target in expected:
            raise ValueError('duplicate installed file mapping: ' + target)
        expected[target] = sha256
    for target, sha256 in expected.items():
        path = root / target
        if not path.is_file() or digest(path) != sha256:
            raise ValueError('installed file differs from canonical manifest: ' + target)
    # These are generated by the adapters rather than copied from the bundle.
    generated = {'usr/share/doc/memveil/copyright',
                 'usr/share/doc/memveil/changelog.Debian.gz'}
    for prefix in ('usr/share/memveil/docs', 'usr/share/doc/memveil'):
        for path in (root / prefix).rglob('*'):
            if path.is_file():
                target = path.relative_to(root).as_posix()
                if target not in expected and target not in generated:
                    raise ValueError('extra installed file outside canonical manifest: ' + target)


def inventory(root, installed=False):
    root = Path(root)
    if root.is_symlink():
        raise ValueError('runtime root is a symlink')
    prefixes = ('usr/bin', 'usr/lib/memveil', 'usr/share/memveil/profiles') if installed else ('bin', 'lib', 'bpf', 'profiles')
    entries = []
    runtime_files = set()
    def walk_error(error):
        raise error
    for prefix in prefixes:
        base = root / prefix
        for parent in (base, *base.parents):
            if parent == root.parent:
                break
            if parent.is_symlink():
                raise ValueError('runtime directory is a symlink: ' + str(parent))
        if not base.is_dir():
            raise ValueError('missing runtime directory: ' + prefix)
        for current, dirs, files in os.walk(base, onerror=walk_error):
            for leaf in dirs + files:
                path = Path(current) / leaf
                mode = path.lstat().st_mode
                if stat.S_ISLNK(mode) or not (stat.S_ISDIR(mode) or stat.S_ISREG(mode)):
                    raise ValueError('unsupported runtime entry: ' + str(path))
            for leaf in sorted(files):
                path = Path(current) / leaf
                name = path.relative_to(root).as_posix()
                runtime_files.add(name)
                if installed:
                    if name.startswith('usr/lib/memveil/') and name.endswith('.bpf.o'):
                        name = 'bpf/' + name[len('usr/lib/memveil/'):]
                    elif name.startswith('usr/share/memveil/'):
                        name = name[len('usr/share/memveil/'):]
                    else:
                        name = name[4:]
                if name.startswith('lib/') and not name.startswith('lib/memveil/'):
                    raise ValueError('noncanonical library path: ' + name)
                size = str(path.stat().st_size)
                parse_size(size)
                entries.append({'type': 'file', 'path': name, 'sha256': digest(path), 'size': size})
    # An exclusive extracted package must not hide runtime objects elsewhere.
    for current, dirs, files in os.walk(root, onerror=walk_error):
        for leaf in dirs + files:
            path = Path(current) / leaf
            mode = path.lstat().st_mode
            if not (stat.S_ISREG(mode) or stat.S_ISDIR(mode)):
                raise ValueError('unsupported package entry: ' + str(path))
        for leaf in files:
            path = Path(current) / leaf
            name = path.relative_to(root).as_posix()
            if name in runtime_files:
                continue
            with path.open('rb') as stream:
                elf = stream.read(4) == b'\x7fELF'
            if elf or re.search(r'\.so(?:\.|$)', leaf) or leaf.endswith('.bpf.o'):
                raise ValueError('runtime entry outside canonical layout: ' + name)
    return sorted(entries, key=lambda entry: entry['path'])


def verify(root, expected, installed=False):
    expected_sizes = [parse_size(entry['size']) for entry in expected]
    actual = inventory(root, installed)
    if actual != expected or [parse_size(entry['size']) for entry in actual] != expected_sizes:
        raise ValueError('runtime inventory differs from canonical manifest')
    return actual


def verify_bundle(root):
    root = Path(root)
    manifest = json.loads((root / 'MANIFEST.json').read_text())
    runtime = manifest['canonical_runtime']
    if runtime['format'] != FORMAT:
        raise ValueError('unsupported canonical runtime format')
    if runtime.get('cpu') != runtime_cpu.CONTRACT:
        raise ValueError('unsupported canonical runtime CPU contract')
    verify(root, runtime['entries'])
    runtime_cpu.verify_engine(root / 'bin/memveil')
    actual = {}
    for current, dirs, files in os.walk(root):
        for name in dirs + files:
            path = Path(current) / name
            mode = path.lstat().st_mode
            if not (stat.S_ISREG(mode) or stat.S_ISDIR(mode)):
                raise ValueError('unsupported bundle entry: ' + str(path))
        for name in files:
            path = Path(current) / name
            relative = path.relative_to(root).as_posix()
            if relative != 'MANIFEST.json':
                actual[relative] = digest(path)
    if actual != manifest['files']:
        raise ValueError('bundle files differ from manifest')
    return manifest


def verify_sources(root, manifest, bridge_archive):
    """Bind RPM source inputs without rebuilding or granting qualification."""
    import source_inventory
    root = Path(root)
    lock = json.loads((root / 'toolchain.lock.json').read_text())
    pinned = lock['dependencies']['libbpf-mojo']
    if digest(bridge_archive) != pinned['tarball_sha256']:
        raise ValueError('bridge archive differs from the source lock')
    for key in ('version', 'source_commit', 'tarball_sha256'):
        if manifest['libbpf_mojo'][key] != pinned[key]:
            raise ValueError('bundle library identity differs from the source lock')
    current = source_inventory.take_inventory(root)
    def portable(entries):
        return [{key: value for key, value in entry.items()
                 if key not in ('mtime_ns', 'ctime_ns')} for entry in entries]
    if any(entry['kind'] not in ('file', 'dir') for entry in current['files']):
        raise ValueError('unsupported source inventory entry')
    if (current['digest'] != manifest['source_inventory_digest'] or
            portable(current['files']) != portable(manifest['source_inventory'])):
        raise ValueError('source inventory differs from the canonical build')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    inputs = parser.add_mutually_exclusive_group(required=True)
    inputs.add_argument('--bundle')
    inputs.add_argument('--manifest', help='previously verified private manifest snapshot')
    parser.add_argument('--save-manifest', help='save verified expectations before copying')
    parser.add_argument('--installed')
    parser.add_argument('--source-tree')
    parser.add_argument('--bridge-archive')
    args = parser.parse_args()
    if bool(args.source_tree) != bool(args.bridge_archive):
        parser.error('--source-tree and --bridge-archive must be supplied together')
    if args.manifest and (not args.installed or args.source_tree or args.save_manifest):
        parser.error('--manifest requires --installed and cannot verify or save source inputs')
    try:
        manifest = (json.loads(Path(args.manifest).read_text()) if args.manifest
                    else verify_bundle(args.bundle))
        if args.source_tree:
            verify_sources(args.source_tree, manifest, args.bridge_archive)
        if args.installed:
            verify_installed(args.installed, manifest)
        if args.save_manifest:
            with open(args.save_manifest, 'x') as stream:
                json.dump(manifest, stream, sort_keys=True)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, 'canonical-runtime: ' + str(error) + '\n')
    print('canonical-runtime: exact bytes verified; qualification not asserted')
